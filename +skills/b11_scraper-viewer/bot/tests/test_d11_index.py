"""Mac output folder and the d11_files.js index. No network."""

from __future__ import annotations

import json
import os
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import constants  # noqa: E402
import extract_url  # noqa: E402
import scrape_options as scrape  # noqa: E402


class OutputDirectoryTests(unittest.TestCase):
    def test_mac_default_and_bot_home(self):
        self.assertEqual(
            constants.MAC_OUTPUT_DIR,
            "/Users/Shared/Repos/GrokBot_/+data/DBMSs/JSONs/d11_scraper-viewer",
        )
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp) / "home"
            previous = os.environ.pop(constants.MAC_OUTPUT_ENV, None)
            try:
                self.assertEqual(constants.output_directory("mac"), Path(constants.MAC_OUTPUT_DIR))
                self.assertEqual(
                    constants.output_directory("bot", home),
                    home / "Tools" / "lean-input" / "output",
                )
                override = Path(tmp) / "data"
                os.environ[constants.MAC_OUTPUT_ENV] = str(override)
                self.assertEqual(constants.output_directory("mac"), override)
            finally:
                if previous is None:
                    os.environ.pop(constants.MAC_OUTPUT_ENV, None)
                else:
                    os.environ[constants.MAC_OUTPUT_ENV] = previous

    def test_index_lists_every_json_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            folder = Path(tmp)
            page = {"requested_url": "https://example.com/", "text": "café"}
            (folder / "page-1.json").write_text(json.dumps(page), encoding="utf-8")
            (folder / "page-1.metrics.json").write_text("{}", encoding="utf-8")
            (folder / "broken.json").write_text("{", encoding="utf-8")
            (folder / "notes.txt").write_text("skip", encoding="utf-8")
            index = extract_url.rebuild_d11_files(folder)
            text = index.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("// Generated by c11_build-files.mjs. Do not edit.\nwindow.D11_FILES = "))
            self.assertTrue(text.endswith(";\n"))
            payload = json.loads(text.split("=", 1)[1].strip().rstrip(";"))
            by_name = {item["name"]: item for item in payload}
            self.assertEqual(set(by_name), {"page-1.json", "page-1.metrics.json", "broken.json"})
            self.assertEqual(by_name["page-1.json"]["data"]["text"], "café")
            self.assertEqual(by_name["page-1.json"]["size"], (folder / "page-1.json").stat().st_size)
            self.assertIn("Could not parse JSON:", by_name["broken.json"]["data"]["error"])
            self.assertNotIn("d11_files.js", by_name)

    def test_mac_run_rewrites_the_index(self):
        html = "<html><head><title>Garden</title></head><body><p>Kale</p></body></html>"

        def fake(url, allow_tunnel=False, require_html=False, lock_origin=None):
            return {"ok": True, "final_url": url, "http_status": 200, "text": html, "warnings": [], "error": None}

        with tempfile.TemporaryDirectory() as tmp:
            folder = Path(tmp) / "d11"
            previous = os.environ.get(constants.MAC_OUTPUT_ENV)
            os.environ[constants.MAC_OUTPUT_ENV] = str(folder)
            try:
                stem = folder / "page-run.json"
                code, _summary, written = scrape.run_selected(
                    ["page", "seo"], "https://example.com/garden", stem, fetcher=fake,
                )
                index = extract_url.publish_mac_index(written)
            finally:
                if previous is None:
                    os.environ.pop(constants.MAC_OUTPUT_ENV, None)
                else:
                    os.environ[constants.MAC_OUTPUT_ENV] = previous
            self.assertIn(code, (0, 1))
            text = Path(index).read_text(encoding="utf-8")
            payload = json.loads(text.split("=", 1)[1].strip().rstrip(";"))
            names = {item["name"] for item in payload}
            self.assertIn("page-run.json", names)
            self.assertIn("page-run.seo.json", names)
            self.assertIn("page-run.metrics.json", names)
            self.assertIn("page-run.seo.metrics.json", names)
            self.assertTrue(folder.is_dir())


if __name__ == "__main__":
    unittest.main()
