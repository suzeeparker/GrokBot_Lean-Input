// Rebuilds ../../../+data/DBMSs/JSONs/d11_scraper-viewer/d11_files.js so index.html
// lists every JSON file in that folder when opened straight from Finder.
// Run: node c11_build-files.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir  = path.resolve(here, '../../../+data/DBMSs/JSONs/d11_scraper-viewer');
fs.mkdirSync(dir, { recursive: true });

const files = fs.readdirSync(dir).filter(n => n.toLowerCase().endsWith('.json')).map(name => {
  const p = path.join(dir, name), st = fs.statSync(p);
  let data;
  try { data = JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { data = { error: 'Could not parse JSON: ' + e.message }; }
  return { name, mtime: st.mtimeMs, size: st.size, data };
});

fs.writeFileSync(path.join(dir, 'd11_files.js'),
  '// Generated by c11_build-files.mjs. Do not edit.\nwindow.D11_FILES = ' + JSON.stringify(files) + ';\n');
console.log(`${files.length} JSON files listed in ${path.join(dir, 'd11_files.js')}`);
